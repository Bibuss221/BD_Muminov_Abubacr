-- Живые SQL-запросы для лабораторной работы №1–2.
-- Запускаются после создания структуры и заполнения базы.

-- 1. Проверка количества записей во всех отношениях.
SELECT
    (SELECT COUNT(*) FROM Клиент) AS клиентов,
    (SELECT COUNT(*) FROM Автомобиль) AS автомобилей,
    (SELECT COUNT(*) FROM Сделка) AS сделок,
    (SELECT COUNT(*) FROM Скидка) AS скидок,
    (SELECT COUNT(*) FROM Штраф) AS штрафов,
    (SELECT COUNT(*) FROM Применение_скидки) AS применений_скидок;

-- 2. Основные сведения об автомобилях.
SELECT
    гос_номер,
    марка,
    тип,
    стоимость,
    год_выпуска
FROM Автомобиль
ORDER BY марка, гос_номер
LIMIT 20;

-- 3. Сделки с соединением клиентов и автомобилей.
SELECT
    s.id_сделки,
    c.фамилия || ' ' || c.имя AS клиент,
    a.марка,
    a.гос_номер,
    s.дата_выдачи,
    s.ожидаемая_дата_возврата,
    s.стоимость_проката
FROM Сделка AS s
JOIN Клиент AS c
    ON c.id_клиента = s.id_клиента
JOIN Автомобиль AS a
    ON a.гос_номер = s.гос_номер
ORDER BY s.дата_выдачи, s.id_сделки
LIMIT 20;

-- 4. Группировка: количество сделок и выручка по автомобилям.
SELECT
    a.марка,
    a.тип,
    COUNT(s.id_сделки) AS количество_сделок,
    COALESCE(SUM(s.стоимость_проката), 0) AS выручка
FROM Автомобиль AS a
LEFT JOIN Сделка AS s
    ON s.гос_номер = a.гос_номер
GROUP BY a.марка, a.тип
ORDER BY выручка DESC;

-- 5. HAVING: клиенты с двумя и более сделками.
SELECT
    c.id_клиента,
    c.фамилия,
    c.имя,
    COUNT(s.id_сделки) AS количество_сделок
FROM Клиент AS c
JOIN Сделка AS s
    ON s.id_клиента = c.id_клиента
GROUP BY c.id_клиента, c.фамилия, c.имя
HAVING COUNT(s.id_сделки) >= 2
ORDER BY количество_сделок DESC;

-- 6. Связь многие-ко-многим между сделками и скидками.
SELECT
    s.id_сделки,
    s.стоимость_проката,
    d.размер_скидки,
    d.условие
FROM Сделка AS s
JOIN Применение_скидки AS ps
    ON ps.id_сделки = s.id_сделки
JOIN Скидка AS d
    ON d.id_скидки = ps.id_скидки
ORDER BY s.id_сделки
LIMIT 20;

-- 7. Сумма штрафов по клиентам.
SELECT
    c.фамилия,
    c.имя,
    SUM(p.сумма_штрафа) AS сумма_штрафов
FROM Клиент AS c
JOIN Сделка AS s
    ON s.id_клиента = c.id_клиента
JOIN Штраф AS p
    ON p.id_сделки = s.id_сделки
GROUP BY c.id_клиента, c.фамилия, c.имя
ORDER BY сумма_штрафов DESC
LIMIT 20;

